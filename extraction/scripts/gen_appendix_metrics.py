#!/usr/bin/env python3
"""Generates latex-article/appendix_metrics.tex from the metric inventory.

Longtable rows with the canonical metrics of the 9 categories of the
codebook, sorted by category and frequency. Buckets outside the taxonomy
(business, code-level, etc.) remain only in the CSV of the package.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INV = ROOT / 'data' / 'master' / 'metric_inventory.csv'
OUT = ROOT / 'latex-article' / 'appendix_metrics.tex'

ORDER = ['ProdPerf', 'SurveyPerc', 'Satisf', 'Collab', 'Quality',
         'Activity', 'Agile', 'Delivery', 'DevExDim']
LBL = {'ProdPerf': 'Productivity / Performance',
       'SurveyPerc': 'Survey / Perceptual',
       'Satisf': 'Satisfaction / Wellbeing',
       'Collab': 'Collaboration',
       'Quality': 'Quality',
       'Activity': 'Activity / Code',
       'Agile': 'Agile / Process',
       'Delivery': 'Delivery Performance',
       'DevExDim': 'DevEx Dimensions'}


def tex_escape(s):
    return s.replace('&', r'\&').replace('%', r'\%').replace('#', r'\#')


def main():
    rows = [r for r in list(csv.reader(open(INV)))[1:] if r[0] in ORDER]
    rows.sort(key=lambda r: (ORDER.index(r[0]), -int(r[2]), r[1]))
    header = (r'\textbf{Metric} & \textbf{$n$ (acad./grey)} & '
              r'\textbf{Sources} \\')
    lines = [
        '% Auto-generated by extraction/scripts/gen_appendix_metrics.py',
        '% Do not edit by hand; regenerate from data/master/metric_inventory.csv',
        r'\begin{longtable}{>{\raggedright\arraybackslash}p{4.0cm} '
        r'>{\centering\arraybackslash}p{1.4cm} p{6.8cm}}',
        r'\caption{Concrete metric inventory by category. $n$ splits into '
        r'academic/grey sources.} \label{tab:metric_inventory_full} \\',
        r'\toprule', header, r'\midrule', r'\endfirsthead',
        r'\multicolumn{3}{l}{\textit{Table~\ref{tab:metric_inventory_full} '
        r'continued from previous page}} \\',
        r'\toprule', header, r'\midrule', r'\endhead',
        r'\midrule',
        r'\multicolumn{3}{r}{\textit{Continued on next page}} \\',
        r'\endfoot',
        r'\bottomrule', r'\endlastfoot',
    ]
    prev = None
    for cat, metric, n, acad, grey, sources in rows:
        if cat != prev:
            if prev is not None:
                lines.append(r'\midrule')
            lines.append(
                r'\multicolumn{3}{l}{\textit{\textbf{%s}}} \\' % LBL[cat])
            prev = cat
        refs = ', '.join(r'\refS{%s}' % s for s in sources.split(';'))
        lines.append(r'%s & %s (%s/%s) & [%s] \\'
                     % (tex_escape(metric[0].upper() + metric[1:]), n, acad, grey, refs))
    lines.append(r'\end{longtable}')
    OUT.write_text('\n'.join(lines) + '\n')
    print('ok', OUT, '|', len(rows), 'metrics')


if __name__ == '__main__':
    main()
