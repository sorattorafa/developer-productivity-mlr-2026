def esc(s):
    s = s.replace("\\&", "&")
    return re.sub(r"([&%#_$])", r"\\\1", s)


def row(i, a, y, t):
    return r"\refstepcounter{study}\thestudy\label{s:%s} & %s & %s & %s \\" % (i, a, y, esc(t))


wb = openpyxl.load_workbook(MASTER, read_only=True, data_only=True)
acad = [(r[0], int(str(r[3])[:4]), TITLE.get(r[0], r[1]).strip())
        for r in list(wb["Included Papers"].iter_rows(values_only=True))[1:]
        if r[55] == STREAM and str(r[30]).strip() == "Include"]
grey = [(r[0], int(str(r[4])[:4]), TITLE.get(r[0], r[1]).strip())
        for r in list(wb["Grey Literature"].iter_rows(values_only=True))[1:]
        if r[47] == STREAM and str(r[19]).strip() == "Include"]
assert len(acad) == 81 and len(grey) == 18, (len(acad), len(grey))
missing = [i for i, _, _ in acad + grey if i not in AUTH]
assert not missing, missing
acad.sort(key=lambda x: (-x[1], x[2].lower()))
grey.sort(key=lambda x: x[0])
for src, items in ((ACAD, acad), (GL, grey)):
    old = Path(src).read_text(encoding="utf-8")
    assert MARK not in old, "update block already present in " + src
    labels = set(re.findall(r"\\label\{s:([^}]+)\}", old))
    assert not labels & {i for i, _, _ in items}, "duplicate label"
    block = [MARK] + [row(i, AUTH[i], y, t) for i, y, t in items]
    out = Path(OUT) / Path(src).name
    out.write_text(old.rstrip("\n") + "\n\n" + "\n".join(block) + "\n", encoding="utf-8")
    print(out, len(labels), "+", len(items))
